/**
 * The manifest behind `pnpm og` — `src/lib/og.generated.ts`, the list of page
 * cards that have actually been captured.
 *
 * It lives here rather than in `scripts/build-og.mjs` so it can be tested
 * without launching Chrome. Reasoning: `docs/per-page-og-images.md`.
 */

/** The slugs a manifest source claims. Anything unparseable reads as empty. */
export function parseManifest(source) {
  const open = source.indexOf("[")
  if (open < 0) return []
  const body = source.slice(open, source.lastIndexOf("]"))
  return [...body.matchAll(/"([^"]+)"/g)].map((match) => match[1])
}

/**
 * The union of what the manifest already claims and what a run took, minus
 * anything whose PNG is no longer on disk.
 *
 * Merging is what lets `pnpm og --only <new-machine>` be the whole card step a
 * new machine owes: replacing would shrink the list to the one slug it just
 * captured and send the other two hundred pages back to the site card.
 * Filtering on `exists` is what keeps a deleted machine from lingering in it —
 * `og.test.ts` fails a manifest that names a file that is not there.
 */
export function mergeManifest(claimed, captured, exists) {
  return [...new Set([...claimed, ...captured])].filter(exists).sort()
}

/** The generated module, as text. */
export function manifestSource(slugs) {
  return [
    "/**",
    " * GENERATED by `scripts/build-og.mjs` — do not edit.",
    " *",
    " * The page cards under `public/og/` that have actually been captured. Read by",
    " * `src/lib/og.ts` so a page with no card yet falls back to the site card",
    " * rather than to a 404. Notes: `docs/per-page-og-images.md`.",
    " */",
    "",
    "export const capturedOgSlugs: string[] = [",
    ...slugs.map((slug) => `  ${JSON.stringify(slug)},`),
    "]",
    "",
  ].join("\n")
}
